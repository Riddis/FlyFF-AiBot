def eval_bridge_640m_guarded(model) -> dict:
    original = gre.select_persistent_waypoint
    gre.select_persistent_waypoint = select_persistent_waypoint_experimental_invalid_hop_guard
    try:
        import math
        output = {}
        for side in GAP_SIDES:
            specs = held_out_randomized_wall_specs_for_side(N_EVAL_PER_SIDE, gap_side=side, seed=BRIDGE_640M_SEED)
            results = []
            for i, spec in enumerate(specs):
                obstacle = spec.obstacle
                map_model, world = build_multi_wall_world([obstacle])
                cell_size = map_model.native_units_per_cell
                center = MAP_HALF_SIZE_CELLS
                start_native = map_model.layout_to_native(center, center)
                final_native = (
                    start_native[0] + math.cos(FIXED_HEADING) * obstacle.distance_cells * cell_size,
                    start_native[1] + math.sin(FIXED_HEADING) * obstacle.distance_cells * cell_size,
                )
                initial_heading = FIXED_HEADING + spec.approach_heading_offset_radians
                result = run_episode_general_router(
                    model, map_model, world, initial_heading=initial_heading, final_native=final_native,
                    seed=BRIDGE_EPISODE_SEED_BASE + i, use_persistence_controller=False,
                )
                results.append(result)
            output[side] = {"summary": summarize_general_router(results), "episodes": [r.__dict__ for r in results]}
        return output
    finally:
        gre.select_persistent_waypoint = original


