def eval_fixtures_guarded(model) -> list[dict]:
    # Matches scratchpad_routing_regression_fixtures.py's own main()
    # exactly (that dict is a local variable there, not importable).
    seed_base_map = {
        SINGLE_WALL_640M: 925_000_000, TWO_WALL_663M: 935_000_000,
        SINGLE_WALL_705M: 940_000_000, TWO_WALL_706M: 950_000_000,
    }
    original = gre.select_persistent_waypoint
    gre.select_persistent_waypoint = select_persistent_waypoint_experimental_invalid_hop_guard
    try:
        results = []
        for fx in FIXTURES:
            map_model, world, initial_heading, final_native = _spec_and_world(fx)
            episode_seed = seed_base_map[fx.spec_seed] + fx.index
            result_b = run_episode_general_router(model, map_model, world, initial_heading=initial_heading, final_native=final_native, seed=episode_seed, use_persistence_controller=True)
            results.append({"name": fx.name, "outcome_d_with_controller": result_b.outcome})
        return results
    finally:
        gre.select_persistent_waypoint = original


