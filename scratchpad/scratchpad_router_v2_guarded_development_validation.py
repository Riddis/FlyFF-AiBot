def eval_open_stratum(model, manifest: dict, *, episode_seed_base: int) -> dict:
    """Evaluates a manifest's OWN "open" stratum (never done before for
    830M -- MISTAKES.md 2026-08-15). Mirrors eval_held_out's per-episode
    loop exactly, but reconstructs WaypointSpec from the manifest's stored
    fields instead of drawing from a different pool.

    `episode_outcomes` (2026-08-15, per explicit user instruction for the
    820M final rule "D per-episode outcomes identical to A"): the ordered
    per-episode outcome list, not just aggregate counts, so two calls can
    be compared for EXACT identity, not merely equal totals."""
    successes = collisions = timeouts = 0
    episode_outcomes: list[str] = []
    for i, ep in enumerate(manifest["strata"]["open"]["accepted"]):
        spec = WaypointSpec(heading=ep["heading"], bearing=ep["bearing"], distance=ep["distance"], position_offset=tuple(ep["position_offset"]))
        seed = episode_seed_base + i
        raw_env = make_static_waypoint_env(episode_steps=OPEN_EPISODE_STEPS, seed=seed)
        env = StaticWaypointWrapper(NavigationHistoryWrapper(raw_env), spec_source=lambda spec=spec: spec)
        obs, _info = env.reset(seed=seed)
        outcome = "timeout"
        for _tick in range(OPEN_EPISODE_STEPS):
            action, _state = model.predict(obs, deterministic=True)
            obs, reward, term, trunc, info = env.step(action)
            if term:
                if reward >= 1.0:
                    successes += 1
                    outcome = "success"
                elif reward <= -1.0:
                    collisions += 1
                    outcome = "collision"
                break
            if trunc:
                timeouts += 1
                outcome = "timeout"
                break
        else:
            timeouts += 1
        episode_outcomes.append(outcome)
        env.close()
    n = len(manifest["strata"]["open"]["accepted"])
    return {"n": n, "successes": successes, "collisions": collisions, "timeouts": timeouts, "episode_outcomes": episode_outcomes,
            "success_rate": successes / n, "collision_rate": collisions / n}


